        // Unified cooldown gate (used by all hooks)
        // ========================================================================================

        private bool CooldownGate(PassiveCreditKey key, TimeSpan cooldown, string label)
        {
            DateTime now = DateTime.UtcNow;

            if (m_NextPassiveCredit.TryGetValue(key, out DateTime next) && now < next)
            {
                TimeSpan remain = next - now;
                Dbg(PassiveDebugFlags.Cooldown, $"DENY {label} cooldown remaining={remain.TotalSeconds:0.##}s");
                return false;
            }

            m_NextPassiveCredit[key] = now + cooldown;
            Dbg(PassiveDebugFlags.Cooldown, $"CREDITED {label}; nextCreditIn={cooldown.TotalSeconds:0.##}s");
            return true;
        }

        private enum PassiveCreditKind
        {
            Command,
            Feeding,
            TrainingSkill,
            TrainingStat,
            Heal,
            Cure,
            Engagement
        }

        private readonly struct PassiveCreditKey : IEquatable<PassiveCreditKey>
        {
            public readonly PassiveCreditKind Kind;
            public readonly SkillName Skill;
            public readonly StatType Stat;

            public PassiveCreditKey(PassiveCreditKind kind)
            {
                Kind = kind;
                Skill = default;
                Stat = default;
            }

            public PassiveCreditKey(PassiveCreditKind kind, SkillName skill)
            {
                Kind = kind;
                Skill = skill;
                Stat = default;
            }

            public PassiveCreditKey(PassiveCreditKind kind, StatType stat)
            {
                Kind = kind;
                Stat = stat;
                Skill = default;
            }

            public bool Equals(PassiveCreditKey other)
            {
                return Kind == other.Kind && Skill == other.Skill && Stat == other.Stat;
            }

            public override bool Equals(object? obj)
            {
                return obj is PassiveCreditKey other && Equals(other);
            }

            public override int GetHashCode()
            {
                // Cheap composite hash; good enough for small dictionary sizes.
                unchecked
                {
                    int h = (int)Kind;
                    h = (h * 397) ^ (int)Skill;
                    h = (h * 397) ^ (int)Stat;
                    return h;
                }
            }
        }


/*
 * Passive credit collection and gating for controlled creatures.
 *
 * This module is responsible for *observing*, *filtering*, and *weighting*
 * passive training signals generated by pets (commands, skills, stats, healing, etc.),
 * and forwarding normalized credit to the owning player.
 *
 * IMPORTANT:
 * This code does NOT directly modify player skills.
 * It deliberately separates signal collection from reward application.
 *
 * All policy decisions about:
 *   - how passive credit maps to actual player skill gain
 *   - how credit scales with player skill level or progression curves
 *   - how credit is throttled or diminished at higher mastery
 *
 * are handled centrally in PlayerMobile.Passive.cs.
 *
 * This separation ensures:
 *   - exploit mitigation and eligibility rules live close to the signal source
 *   - progression math and tuning live in one player-centric location
 *   - future curve adjustments do not require touching pet or training hooks
 */

/*
 * Passive Gain Rules (BaseCreature.Passive.cs)
 *
 * Common (applies to all hooks before forwarding to PlayerMobile.AddPassivePoints):
 *  - Pet must be a valid controlled creature:
 *      - Controlled == true
 *      - Not Summoned and not IsDeadPet
 *      - ControlMaster exists and is a PlayerMobile
 *  - Owner association must resolve:
 *      - Some hooks require caller == ControlMaster (owner-only), others allow observation via ControlMaster.
 *  - Central anti-exploit gate (CanAwardPassiveCredit):
 *      - No guarded-region “gyms” (pm.Region.IsGuarded)
 *      - No house-region macros (pm.Region is HouseRegion)
 *      - No external mods active (AnyStatMod() || AnySkillMod())
 *      - No owner-controlled pet-vs-pet sparring credit for Training:
 *          - If source == Training and this pet’s Combatant is another BaseCreature controlled by the same owner, deny.
 *  - Unified cooldown gate (CooldownGate):
 *      - All hooks share a single keyed cooldown table (m_NextPassiveCredit).
 *      - Keys vary by hook (e.g., Command, Feeding, TrainingSkill+SkillName, TrainingStat+StatType, Heal, Cure).
 *  - Skill eligibility gate (pm.CanAccruePassiveProgression):
 *      - Do not compute or forward credit if the destination skill cannot currently gain (locked or at cap).
 *      - Prevents “bank while locked/capped” behavior and avoids save/load pollution.
 *  - This module only observes and forwards normalized credit:
 *      - It does NOT directly raise player skills.
 *      - Point->skill conversion and progression curve policy lives in PlayerMobile.Passive.cs.
 *
 * Hook 1: NotifyControlCommandAccepted (source=Command)
 *  - Caller must be the owner (requireOwnerIsCaller: true).
 *  - Command denylist (CanCreditPassiveTamingCommand):
 *      - Denied: None, Drop, Friend, Release, Stay, Stop, Transfer.
 *  - Anti-exploit special rule:
 *      - If order is Attack or Guard AND target is an owner-controlled pet, deny (no pet-vs-pet sparring via commands).
 *  - Cooldown:
 *      - Order-dependent via PassiveTamingCommandCooldown (e.g., Attack~30s, Follow/Guard/Patrol~45s, Come~60s).
 *  - Points:
 *      - Flat 1.0 (placeholder policy).
 *
 * Hook 2: NotifyFeedingLoyaltyImproved (source=Feeding)
 *  - Caller must be the owner (requireOwnerIsCaller: true).
 *  - Must represent real feeding signal:
 *      - itemsConsumed > 0
 *      - endLoyalty > startLoyalty
 *  - Cooldown:
 *      - Feeding key, currently 5 seconds (anti-macro “belt and suspenders”).
 *  - Points:
 *      - Base 1.0
 *      - + up to 2.0 from loyaltyDelta (0.25 per point after the first)
 *      - + up to 1.0 from itemsConsumed (0.10 per item after the first)
 *
 * Hook 3: OnSkillChange (pet skill gain observed; source=Training)
 *  - Observational (requireOwnerIsCaller: false); owner resolved via ControlMaster.
 *  - Only real increases (newBase > oldBase).
 *  - Cooldown:
 *      - Keyed per-skill (TrainingSkill + SkillName) via PassiveTamingTrainingCooldown.
 *      - Meditation uses a longer cooldown than most skills.
 *  - Points:
 *      - Derived from pet skill delta (ComputePassivePointsFromPetGain), capped conservatively.
 *
 * Hook 4: OnAfterStatGain (pet stat gain observed; source=Training)
 *  - Observational (requireOwnerIsCaller: false); owner resolved via ControlMaster.
 *  - Only real increases (newStatRaw > oldStatRaw).
 *  - Cooldown:
 *      - Keyed per-stat (TrainingStat + StatType), currently 8 seconds.
 *  - Points:
 *      - Derived from delta (ComputePassivePointsFromPetStatGain), capped conservatively (<= 2.0).
 *
 * Hook 5: OnHeal (pet healed; source=Training)
 *  - Owner-only (requireOwnerIsCaller: true): other players healing your pet does not credit you.
 *  - Must be a real heal: Hits > oldHits.
 *  - Cooldown:
 *      - Heal key, currently 6 seconds.
 *  - Points:
 *      - Based on amount healed (ComputePassivePointsFromPetHeal), capped (<= 1.0).
 *
 * Hook 6: OnCured (pet cured; source=Training)
 *  - Owner-only (requireOwnerIsCaller: true).
 *  - Event semantics are “success-only” (hook should only fire when a cure occurs).
 *  - Cooldown:
 *      - Cure key, currently 10 seconds.
 *  - Points:
 *      - Fixed 0.75 (placeholder policy), logs oldPoison name if present.
 */


        /// <summary>
        /// Set this in the debugger at runtime to control console output.
        /// Example:
        /// BaseCreature.PassiveDebugFlagsGlobal = BaseCreature.PassiveDebugFlags.Hooks | BaseCreature.PassiveDebugFlags.Points;

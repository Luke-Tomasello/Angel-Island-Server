        // Central anti-exploit rule for *all* passive-credit hooks.
        // If this returns false, do not award points.
        private bool CanAwardPassiveCredit(PlayerMobile pm, PlayerMobile.PassiveGainSource source, out string denyReason)
        {
            denyReason = null;

            if (pm == null || pm.Deleted)
            {
                denyReason = "pm null/deleted";
                return false;
            }

            // No “safe-zone gyms”
            if (pm.Region != null && pm.Region.IsGuarded)
            {
                denyReason = "in guarded region";
                return false;
            }

            // No “house macros”
            if (pm.Region is HouseRegion)
            {
                denyReason = "in house region";
                return false;
            }

            // No “boat gyms”
            if (BaseBoat.FindBoatAt(pm) != null)
            {
                denyReason = "on a boat";
                return false;
            }

            // No buff/equip/stat/skill mod exploitation (applies to all hooks)
            if (HasAnyExternalTrainingMod())
            {
                denyReason = "external training mod active";
                return false;
            }

            // Prevent passive training credit from owner-controlled pet-vs-pet combat.
            if (source == PlayerMobile.PassiveGainSource.Training &&
                IsFightingOwnerControlledPet(pm))
            {
                denyReason = "combatant is owner-controlled pet";
                return false;
            }

            return true;
        }

        private bool HasAnyExternalTrainingMod()
        {
            return AnyStatMod() || AnySkillMod();
        }
        private bool IsFightingOwnerControlledPet(PlayerMobile owner)
        {
            if (owner == null)
                return false;

            if (Combatant is not BaseCreature other)
                return false;

            if (!other.Controlled)
                return false;

            if (other.ControlMaster != owner)
                return false;

            return true;
        }
        private static bool HasRecentOwnerDamage(BaseCreature target, PlayerMobile owner)
        {
            if (target == null || target.Deleted || owner == null || owner.Deleted)
                return false;

            var entries = target.DamageEntries;
            if (entries == null || entries.Count == 0)
                return false;

            for (int i = 0; i < entries.Count; i++)
            {
                if (entries[i] is not DamageEntry de)
                    continue;

                if (de.HasExpired)
                    continue;

                Mobile damager = de.Damager;
                if (damager == null || damager.Deleted)
                    continue;

                // Attribute controlled pet damage to owner (ControlMaster)
                if (damager is BaseCreature bc)
                {
                    Mobile master = bc.ControlMaster;
                    if (master != null && !master.Deleted)
                        damager = master;
                }

                if (damager == owner)
                    return true;
            }

            return false;
        }

        private bool IsOwnerControlledPetTarget(PlayerMobile owner, Mobile? target)
        {
            if (owner == null || target == null)
                return false;

            if (target is BaseCreature bc && bc.Controlled && bc.ControlMaster == owner)
                return true;

            return false;
        }

        private bool HardStop()
        {
            // make sure the system is on
            if (!CoreAI.IsDynamicFeatureSet(CoreAI.FeatureBits.PassiveTamingEnabled))
                return true;

            // Existing “no spam during server-up / unnamed pets” guard (kept)
            if (string.IsNullOrEmpty(Name) || ControlMaster == null)
                return true;

            // Hirelings are intentionally excluded from passive Taming.
            // They are paid, commandable NPCs (not tameable animals) and should not
            // contribute to skill progression, even though they accept commands.
            if (this is BaseHire)
                return true;

            return false;
        }
        private bool TryResolveOwnerPlayer(Mobile caller, bool requireOwnerIsCaller, out PlayerMobile pm, out string denyReason)
        {
            pm = null;
            denyReason = null;

            if (caller == null)
            {
                denyReason = "caller == null";
                return false;
            }

            if (caller.Deleted)
            {
                denyReason = "caller.Deleted";
                return false;
            }

            if (Deleted)
            {
                denyReason = "pet.Deleted";
                return false;
            }

            if (!Controlled)
            {
                denyReason = "!Controlled";
                return false;
            }

            if (Summoned || IsDeadPet)
            {
                denyReason = $"Summoned={Summoned} || IsDeadPet={IsDeadPet}";
                return false;
            }

            if (ControlMaster == null || ControlMaster.Deleted)
            {
                denyReason = "ControlMaster null/deleted";
                return false;
            }

            if (requireOwnerIsCaller && caller != ControlMaster)
            {
                denyReason = "caller != ControlMaster";
                return false;
            }

            if (ControlMaster is not PlayerMobile ownerPm)
            {
                denyReason = "ControlMaster is not PlayerMobile";
                return false;
            }

            pm = ownerPm;
            return true;
        }

        private bool CanCreditPassiveTamingCommand(OrderType order)
        {
            // Denylist is intentionally conservative; these can be spammed with low/no gameplay signal.
            switch (order)
            {
                case OrderType.None:
                case OrderType.Drop:
                case OrderType.Friend:
                case OrderType.Release:
                case OrderType.Stay:
                case OrderType.Stop:
                case OrderType.Transfer:
                    Dbg(PassiveDebugFlags.DenyList, $"DENY denylist order={order}");
                    return false;
            }

            Dbg(PassiveDebugFlags.Command, $"ALLOW CanCreditPassiveTamingCommand order={order}");
            return true;
        }
        private static bool IsComeOrFollow(OrderType o)
        {
            return o == OrderType.Come || o == OrderType.Follow;
        }

        /// <summary>
        /// Gate: deny command credit when the command does not change the pet's effective control order.
        /// - If the pet is already doing the same order: deny ("already doing that").
        /// - Treat Come/Follow as equivalent intent: if both are in {Come, Follow}, deny.
        /// </summary>
        private static bool IsRedundantControlOrder(BaseCreature pet, OrderType incomingOrder)
        {
            if (pet == null || pet.Deleted)
                return true; // conservative: no pet -> no credit

            OrderType current = pet.ControlOrder;

            // Exact match
            if (incomingOrder == current)
                return true;

            // Come/Follow equivalence: if both are "come/follow intent", treat as redundant.
            if (IsComeOrFollow(incomingOrder) && IsComeOrFollow(current))
                return true;

            return false;
        }
        private TimeSpan PassiveTamingCommandCooldown(OrderType order)
        {
            // Estimated values are fine (per your note). These should be tuned later against logs.
            return order switch
            {
                OrderType.Attack => TimeSpan.FromMilliseconds(CoreAI.CmdAttackCoolMs),
                OrderType.Come => TimeSpan.FromMilliseconds(CoreAI.CmdComeCoolMs),
                OrderType.Guard => TimeSpan.FromMilliseconds(CoreAI.CmdGuardCoolMs),
                OrderType.Follow => TimeSpan.FromMilliseconds(CoreAI.CmdFollowCoolMs),
                OrderType.Patrol => TimeSpan.FromMilliseconds(CoreAI.CmdPatrolCoolMs),
                _ => TimeSpan.FromMilliseconds(CoreAI.CmdDefaultCoolMs)
            };
        }
        private bool PassiveTamingCommandCooldownBlocked(OrderType order)
        {
            return order switch
            {
                OrderType.Attack => CoreAI.IsDynamicFeatureSet(CoreAI.FeatureBits.CmdAttackBlock),
                OrderType.Come => CoreAI.IsDynamicFeatureSet(CoreAI.FeatureBits.CmdComeBlock),
                OrderType.Guard => CoreAI.IsDynamicFeatureSet(CoreAI.FeatureBits.CmdGuardBlock),
                OrderType.Follow => CoreAI.IsDynamicFeatureSet(CoreAI.FeatureBits.CmdFollowBlock),
                OrderType.Patrol => CoreAI.IsDynamicFeatureSet(CoreAI.FeatureBits.CmdPatrolBlock),
                _ => CoreAI.IsDynamicFeatureSet(CoreAI.FeatureBits.CmdDefaultBlock)
            };
        }


        private TimeSpan PassiveTamingTrainingCooldown(SkillName sn)
        {
            // High-churn skills get a longer cooldown; everything else gets a short one.
            // This replaces the previous “per-skill dictionary” with the unified cooldown gate.
            return sn == SkillName.Meditation
                ? TimeSpan.FromMilliseconds(CoreAI.SkillMeditationCoolMs)
                : TimeSpan.FromMilliseconds(CoreAI.SkillDefaultCoolMs);
        }
        private bool PassiveTamingTrainingCooldownBlock(SkillName sn)
        {
            // High-churn skills get their own block switch; everything else uses the default.
            return sn == SkillName.Meditation
                ? CoreAI.IsDynamicFeatureSet(CoreAI.FeatureBits.SkillMeditationBlock)
                : CoreAI.IsDynamicFeatureSet(CoreAI.FeatureBits.SkillDefaultBlock);
        }


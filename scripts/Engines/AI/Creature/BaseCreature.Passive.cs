        // ========================================================================================
        // Hook 1: Accepted command (already passed CheckControlChance in caller)
        // ========================================================================================
        public void NotifyControlCommandAccepted(Mobile from, OrderType order, Mobile? target = null)
        {
            // System disabled, no owner, no name (server-up spam)
            if (HardStop())
                return;

            // tracking for this hook blocked
            if (PassiveTamingCommandCooldownBlocked(order))
            {
                Dbg(PassiveDebugFlags.Gate, $"DENY credit (blocked) source=Command order={order}");
                return;
            }

            Dbg(PassiveDebugFlags.Command, $"ENTER order={order} target={(target != null ? GetSafeName(target) : "<null>")}");

            // Shared baseline gates for this family of credit
            if (!TryResolveOwnerPlayer(from, requireOwnerIsCaller: true, out PlayerMobile pm, out string deny))
            {
                Dbg(PassiveDebugFlags.Gate, $"EXIT ({deny})");
                return;
            }

            // Do not award passive training credit for commands that cause a player’s own pets to fight each other.
            // This prevents safe, owner-controlled pet-vs-pet sparring from generating training gains.
            if ((order == OrderType.Attack || order == OrderType.Guard) && IsOwnerControlledPetTarget(pm, target))
            {
                Dbg(PassiveDebugFlags.Gate,
                    $"DENY credit (target is owner-controlled pet) source=Command order={order} target={GetSafeName(target)}");
                return;
            }

            // Source-wide “no gyms / no house macros / no mods” rule
            if (!CanAwardPassiveCredit(pm, PlayerMobile.PassiveGainSource.Command, out deny))
            {
                Dbg(PassiveDebugFlags.Gate, $"DENY credit ({deny}) source=Command");
                return;
            }

            // Command-specific denylist gate (special needs are fine)
            if (!CanCreditPassiveTamingCommand(order))
            {
                Dbg(PassiveDebugFlags.Command, $"EXIT (CanCreditPassiveTamingCommand=false) order={order}");
                return;
            }

            // Unified cooldown gate (command cooldown depends on order)
            TimeSpan cd = PassiveTamingCommandCooldown(order);
            if (!CooldownGate(new PassiveCreditKey(PassiveCreditKind.Command), cd, $"command:{order}"))
                return;

            // Do not compute or forward passive credit if the destination skill cannot currently gain (locked or at cap).
            if (!pm.CanAccruePassiveProgression(PlayerMobile.PassiveProgressionBucket.AnimalTaming, out string reason))
            {
                Dbg(PassiveDebugFlags.Gate, $"DENY accrue bucket=AnimalTaming source=Command ({reason})");
                return;
            }

            // Deny credit for redundant/no-op commands.
            // - Same order as current ControlOrder => no state change.
            // - Come/Follow are treated as equivalent intent.
            if (IsRedundantControlOrder(this, order))
            {
                Dbg(PassiveDebugFlags.Gate, $"DENY accrue bucket=AnimalTaming source=Command (already doing that) cmd={order} cur={this.ControlOrder}");
                return;
            }

            // Points policy (supportive-only):
            // Engagement is the primary progression driver. Commands are frequent and player-paced,
            // so keep their raw contribution small; weighting + pre-engagement cap enforce limits.
            double points = (order == OrderType.Attack || order == OrderType.Guard)
                ? 0.15
                : 0.10;

            Dbg(PassiveDebugFlags.Points, $"POINTS computed={points:0.###} source=Command bucket=AnimalTaming");

            pm.AddPassivePoints(
                PlayerMobile.PassiveGainSource.Command,
                PlayerMobile.PassiveProgressionBucket.AnimalTaming,
                points,
                pet: this,
                context: target ?? (object)order
            );

            Dbg(PassiveDebugFlags.Forwarding, "FORWARDED to PlayerMobile.AddPassivePoints(source=Command)");
        }

        // ========================================================================================
        // Hook 2: Feeding with loyalty improvement
        // ========================================================================================
        public void NotifyFeedingLoyaltyImproved(Mobile from, Item dropped, int startLoyalty, int endLoyalty, int itemsConsumed)
        {
            // System disabled, no owner, no name (server-up spam)
            if (HardStop())
                return;

            // Block gate (live ops / tuning)
            if (CoreAI.IsDynamicFeatureSet(CoreAI.FeatureBits.FeedingBlock))
            {
                Dbg(PassiveDebugFlags.Gate, "DENY credit (blocked) source=Feeding");
                return;
            }

            Dbg(PassiveDebugFlags.Feeding,
                $"ENTER startLoyalty={startLoyalty} endLoyalty={endLoyalty} itemsConsumed={itemsConsumed} item={(dropped != null ? dropped.GetType().Name : "<null>")}");

            if (!TryResolveOwnerPlayer(from, requireOwnerIsCaller: true, out PlayerMobile pm, out string deny))
            {
                Dbg(PassiveDebugFlags.Gate, $"EXIT ({deny})");
                return;
            }

            if (itemsConsumed <= 0)
            {
                Dbg(PassiveDebugFlags.Gate, "EXIT (itemsConsumed <= 0)");
                return;
            }

            if (endLoyalty <= startLoyalty)
            {
                Dbg(PassiveDebugFlags.Gate, "EXIT (endLoyalty <= startLoyalty)");
                return;
            }

            if (!CanAwardPassiveCredit(pm, PlayerMobile.PassiveGainSource.Feeding, out deny))
            {
                Dbg(PassiveDebugFlags.Gate, $"DENY credit ({deny}) source=Feeding");
                return;
            }

            // Unified cooldown gate (feeding is low-value; small cooldown is enough to deter spam)
            // Note: Feeding is already naturally throttled by items + loyalty; this is the anti-macro “belt and suspenders”.
            if (!CooldownGate(new PassiveCreditKey(PassiveCreditKind.Feeding), TimeSpan.FromMilliseconds(CoreAI.FeedingCoolMs), "feeding"))
                return;

            // Do not compute or forward passive credit if the destination skill cannot currently gain (locked or at cap).
            if (!pm.CanAccruePassiveProgression(PlayerMobile.PassiveProgressionBucket.AnimalTaming, out string reason))
            {
                Dbg(PassiveDebugFlags.Gate, $"DENY accrue bucket=AnimalTaming source=Feed ({reason})");
                return;
            }

            int loyaltyDelta = endLoyalty - startLoyalty;
            Dbg(PassiveDebugFlags.Feeding, $"loyaltyDelta={loyaltyDelta}");

            // Feeding is supportive-only (engagement is the primary driver).
            // Goal: typical feeds land ~0.05–0.15 raw; hungry-pet feeds can approach ~0.20–0.25,
            // but should not routinely hit the pre-engagement cap.
            double points = 0.05;

            // Loyalty: gentle linear reward, modest cap.
            // Examples:
            //  - loyaltyDelta  1 => +0.01
            //  - loyaltyDelta 10 => +0.10
            //  - loyaltyDelta 15 => +0.15 (cap)
            if (loyaltyDelta > 0)
                points += Math.Min(0.15, loyaltyDelta * 0.01);

            // Consumption: tiny bonus for multiple items actually consumed, low cap.
            // Examples:
            //  - itemsConsumed 2 => +0.01
            //  - itemsConsumed 6 => +0.05 (cap)
            if (itemsConsumed > 1)
                points += Math.Min(0.05, (itemsConsumed - 1) * 0.01);

            // Local cap (optional but recommended so rawPoints remains sane even if caller changes later).
            if (points > 0.25)
                points = 0.25;

            Dbg(PassiveDebugFlags.Points,
                $"POINTS computed={points:0.###} source=Feeding bucket=AnimalTaming (loyaltyDelta={loyaltyDelta}, itemsConsumed={itemsConsumed})");

            pm.AddPassivePoints(
                PlayerMobile.PassiveGainSource.Feeding,
                PlayerMobile.PassiveProgressionBucket.AnimalTaming,
                points,
                pet: this,
                context: dropped
            );

            Dbg(PassiveDebugFlags.Forwarding, "FORWARDED to PlayerMobile.AddPassivePoints(source=Feeding)");
        }

        // ========================================================================================
        // Hook 3: Pet skill gain observed -> master earns Training points
        // ========================================================================================
        public override void OnSkillChange(SkillName skillName, double oldBase, double newBase)
        {
            base.OnSkillChange(skillName, oldBase, newBase);

            // System disabled, no owner, no name (server-up spam)
            if (HardStop())
                return;

            Skill? skill = Skills?[skillName];
            if (skill == null)
            {
                Dbg(PassiveDebugFlags.PetSkill, $"EXIT (skill lookup failed) skill={skillName}");
                return;
            }

            // tracking for this hook blocked
            if (PassiveTamingTrainingCooldownBlock(skill.SkillName))
            {
                Dbg(PassiveDebugFlags.Gate, $"DENY credit (blocked) source=Skill sn={skill.SkillName}");
                return;
            }

            // Only real increases
            if (newBase <= oldBase)
                return;

            if (!TryResolveOwnerPlayer(ControlMaster, requireOwnerIsCaller: false, out PlayerMobile pm, out string deny))
            {
                Dbg(PassiveDebugFlags.Gate, $"EXIT ({deny})");
                return;
            }

            if (!CanAwardPassiveCredit(pm, PlayerMobile.PassiveGainSource.Training, out deny))
            {
                Dbg(PassiveDebugFlags.Gate, $"DENY credit ({deny}) source=Training");
                return;
            }

            // Unified cooldown gate; training skills are keyed per-skill (so Meditation doesn’t throttle Wrestling, etc.)
            TimeSpan cd = PassiveTamingTrainingCooldown(skill.SkillName);
            if (!CooldownGate(new PassiveCreditKey(PassiveCreditKind.TrainingSkill, skill.SkillName), cd, $"skill:{skill.SkillName}"))
                return;

            // Do not compute or forward passive credit if the destination skill cannot currently gain (locked or at cap).
            if (!pm.CanAccruePassiveProgression(PlayerMobile.PassiveProgressionBucket.AnimalTaming, out string reason))
            {
                Dbg(PassiveDebugFlags.Gate, $"DENY accrue bucket=AnimalTaming source=Skill ({reason})");
                return;
            }

            double delta = newBase - oldBase;

            Dbg(PassiveDebugFlags.PetSkill, $"ENTER skill={skill.SkillName} oldBase={oldBase:0.0##} newBase={newBase:0.0##}");
            Dbg(PassiveDebugFlags.PetSkill, $"delta={delta:0.###}");

            double points = ComputePassivePointsFromPetGain(skill, delta);

            Dbg(PassiveDebugFlags.Points,
                $"POINTS computed={points:0.###} source=Training bucket=AnimalTaming (skill={skill.SkillName}, delta={delta:0.###})");

            if (points <= 0.0)
            {
                Dbg(PassiveDebugFlags.PetSkill, "EXIT (points <= 0)");
                return;
            }

            pm.AddPassivePoints(
                PlayerMobile.PassiveGainSource.Training,
                PlayerMobile.PassiveProgressionBucket.AnimalTaming,
                points,
                pet: this,
                context: skill
            );

            Dbg(PassiveDebugFlags.Forwarding, "FORWARDED to PlayerMobile.AddPassivePoints(source=Training)");
        }

        // ========================================================================================
        // Hook 4: Pet stat gain observed -> master earns Training points
        // ========================================================================================
        protected override void OnAfterStatGain(StatType stat, int oldStatRaw)
        {
            base.OnAfterStatGain(stat, oldStatRaw);

            // System disabled, no owner, no name (server-up spam)
            if (HardStop())
                return;

            // Block gate (live ops / tuning)
            if (CoreAI.IsDynamicFeatureSet(CoreAI.FeatureBits.StatBlock))
            {
                Dbg(PassiveDebugFlags.Gate, $"DENY credit (blocked) source=Stat stat={stat}");
                return;
            }

            Dbg(PassiveDebugFlags.PetStat, $"ENTER stat={stat} oldRaw={oldStatRaw}");

            if (!TryResolveOwnerPlayer(ControlMaster, requireOwnerIsCaller: false, out PlayerMobile pm, out string deny))
            {
                Dbg(PassiveDebugFlags.Gate, $"EXIT ({deny})");
                return;
            }

            if (!CanAwardPassiveCredit(pm, PlayerMobile.PassiveGainSource.Training, out deny))
            {
                Dbg(PassiveDebugFlags.Gate, $"DENY credit ({deny}) source=Training");
                return;
            }

            int newStatRaw = stat switch
            {
                StatType.Str => RawStr,
                StatType.Dex => RawDex,
                StatType.Int => RawInt,
                _ => -1
            };

            if (newStatRaw < 0)
            {
                Dbg(PassiveDebugFlags.PetStat, $"EXIT (unknown stat enum) stat={stat}");
                return;
            }

            if (newStatRaw <= oldStatRaw)
            {
                Dbg(PassiveDebugFlags.PetStat, $"EXIT (no increase) oldRaw={oldStatRaw} newRaw={newStatRaw}");
                return;
            }

            int delta = newStatRaw - oldStatRaw;
            Dbg(PassiveDebugFlags.PetStat, $"delta={delta} (oldRaw={oldStatRaw}, newRaw={newStatRaw})");

            // Unified cooldown gate; stats are keyed per-stat
            if (!CooldownGate(new PassiveCreditKey(PassiveCreditKind.TrainingStat, stat), TimeSpan.FromMilliseconds(CoreAI.StatCoolMs), $"stat:{stat}"))
                return;

            // Do not compute or forward passive credit if the destination skill cannot currently gain (locked or at cap).
            if (!pm.CanAccruePassiveProgression(PlayerMobile.PassiveProgressionBucket.AnimalTaming, out string reason))
            {
                Dbg(PassiveDebugFlags.Gate, $"DENY accrue bucket=AnimalTaming source=Stat ({reason})");
                return;
            }

            double points = ComputePassivePointsFromPetStatGain(stat, delta);

            Dbg(PassiveDebugFlags.Points, $"POINTS computed={points:0.###} source=Training bucket=AnimalTaming (stat={stat}, delta={delta})");

            if (points <= 0.0)
            {
                Dbg(PassiveDebugFlags.PetStat, "EXIT (points <= 0)");
                return;
            }

            pm.AddPassivePoints(
                PlayerMobile.PassiveGainSource.Training,
                PlayerMobile.PassiveProgressionBucket.AnimalTaming,
                points,
                pet: this,
                context: stat
            );

            Dbg(PassiveDebugFlags.Forwarding, "FORWARDED to PlayerMobile.AddPassivePoints(source=Training)");
        }

        // ========================================================================================
        // Hook 5: Pet heal observed -> master earns Training points
        // ========================================================================================
        public override void OnHeal(Mobile source, int oldHits)
        {
            base.OnHeal(source, oldHits);

            // System disabled, no owner, no name (server-up spam)
            if (HardStop())
                return;

            // Block gate (live ops / tuning)
            if (CoreAI.IsDynamicFeatureSet(CoreAI.FeatureBits.HealBlock))
            {
                Dbg(PassiveDebugFlags.Gate, "DENY credit (blocked) source=Heal");
                return;
            }

            // Owner-only: avoid other players healing your pet for your gain
            if (!TryResolveOwnerPlayer(source, requireOwnerIsCaller: true, out PlayerMobile pm, out string deny))
                return;

            if (!CanAwardPassiveCredit(pm, PlayerMobile.PassiveGainSource.Heal, out deny))
            {
                Dbg(PassiveDebugFlags.Gate, $"DENY credit ({deny}) source=Heal");
                return;
            }

            // Your rule: heal credit only for a real heal
            if (Hits <= oldHits)
                return;

            // Unified cooldown gate
            if (!CooldownGate(new PassiveCreditKey(PassiveCreditKind.Heal), TimeSpan.FromMilliseconds(CoreAI.HealCoolMs), "heal"))
                return;

            // Anti-abuse: deny if owner (or owner’s controlled pets) recently damaged this pet.
            // DamageEntries already expire, so this naturally uses a “recent” window.
            if (HasRecentOwnerDamage(this, pm))
            {
                Dbg(PassiveDebugFlags.Gate, "DENY credit (owner recently damaged pet) source=Heal");
                return;
            }

            // Do not compute or forward passive credit if the destination skill cannot currently gain (locked or at cap).
            if (!pm.CanAccruePassiveProgression(PlayerMobile.PassiveProgressionBucket.AnimalTaming, out string reason))
            {
                Dbg(PassiveDebugFlags.Gate, $"DENY accrue bucket=AnimalTaming source=Heal ({reason})");
                return;
            }

            int healed = Hits - oldHits;
            double points = ComputePassivePointsFromPetHeal(healed);

            Dbg(PassiveDebugFlags.Points, $"POINTS computed={points:0.###} source=Heal bucket=AnimalTaming (heal={healed})");

            if (points <= 0.0)
                return;

            pm.AddPassivePoints(
                PlayerMobile.PassiveGainSource.Heal,
                PlayerMobile.PassiveProgressionBucket.AnimalTaming,
                points,
                pet: this,
                context: "Heal"
            );

            Dbg(PassiveDebugFlags.Forwarding, "FORWARDED to PlayerMobile.AddPassivePoints(source=Training)");
        }

        // ========================================================================================
        // Hook 6: Pet cure observed -> master earns Training points
        // ========================================================================================
        public override void OnCured(Mobile from, Poison oldPoison)
        {
            base.OnCured(from, oldPoison);

            // System disabled, no owner, no name (server-up spam)
            if (HardStop())
                return;

            // Block gate (live ops / tuning)
            if (CoreAI.IsDynamicFeatureSet(CoreAI.FeatureBits.CureBlock))
            {
                Dbg(PassiveDebugFlags.Gate, "DENY credit (blocked) source=Cure");
                return;
            }

            // Owner-only: avoid other players curing your pet for your gain
            if (!TryResolveOwnerPlayer(from, requireOwnerIsCaller: true, out PlayerMobile pm, out string deny))
                return;

            if (!CanAwardPassiveCredit(pm, PlayerMobile.PassiveGainSource.Cure, out deny))
            {
                Dbg(PassiveDebugFlags.Gate, $"DENY credit ({deny}) source=Cure");
                return;
            }

            // Unified cooldown gate
            if (!CooldownGate(new PassiveCreditKey(PassiveCreditKind.Cure), TimeSpan.FromMilliseconds(CoreAI.CureCoolMs), "cure"))
                return;

            // Anti-abuse: deny if owner (or owner’s controlled pets) recently damaged this pet.
            // DamageEntries already expire, so this naturally uses a “recent” window.
            if (HasRecentOwnerDamage(this, pm))
            {
                Dbg(PassiveDebugFlags.Gate, "DENY credit (owner recently damaged pet) source=Cure");
                return;
            }

            // Do not compute or forward passive credit if the destination skill cannot currently gain (locked or at cap).
            if (!pm.CanAccruePassiveProgression(PlayerMobile.PassiveProgressionBucket.AnimalTaming, out string reason))
            {
                Dbg(PassiveDebugFlags.Gate, $"DENY accrue bucket=AnimalTaming source=Cure ({reason})");
                return;
            }

            double points = ComputePassivePointsFromPetCure(oldPoison);

            Dbg(PassiveDebugFlags.Points,
                $"POINTS computed={points:0.###} source=Cure bucket=AnimalTaming (cure oldPoison={(oldPoison == null ? "<null>" : oldPoison.Name)})");

            if (points <= 0.0)
                return;

            pm.AddPassivePoints(
                PlayerMobile.PassiveGainSource.Cure,
                PlayerMobile.PassiveProgressionBucket.AnimalTaming,
                points,
                pet: this,
                context: "Cure"
            );

            Dbg(PassiveDebugFlags.Forwarding, "FORWARDED to PlayerMobile.AddPassivePoints(source=Cure)");
        }

        // ========================================================================================
        // Hook 7: Pet gave damage to a wild creature -> master earns Engagement points
        // ========================================================================================
        public override void OnGaveDamage(int amount, Mobile target, bool willKill, DamageContext context)
        {
            base.OnGaveDamage(amount, target, willKill, context);

            // System disabled, no owner, no name (server-up spam)
            if (HardStop())
                return;

            // Block gate (live ops / tuning)
            if (CoreAI.IsDynamicFeatureSet(CoreAI.FeatureBits.GaveDamageBlock))
            {
                Dbg(PassiveDebugFlags.Gate, "DENY credit (blocked) source=Engagement");
                return;
            }

            Dbg(PassiveDebugFlags.Engagement,
                $"ENTER amount={amount} willKill={willKill} target={(target != null ? GetSafeName(target) : "<null>")}");

            // Sanity / meaningful engagement
            if (target == null || target.Deleted)
            {
                Dbg(PassiveDebugFlags.Gate, "EXIT (target null/deleted)");
                return;
            }

            if (amount <= 0)
            {
                Dbg(PassiveDebugFlags.Gate, "EXIT (amount <= 0)");
                return;
            }

            // Engagement is observational: resolve owner via ControlMaster (no caller semantics)
            if (!TryResolveOwnerPlayer(ControlMaster, requireOwnerIsCaller: false, out PlayerMobile pm, out string deny))
            {
                Dbg(PassiveDebugFlags.Gate, $"EXIT ({deny})");
                return;
            }

            // Only credit for fighting "wild" creatures (exclude players and controlled pets).
            // If you want to allow certain NPC types that aren't BaseCreature, loosen this gate later.
            if (target is not BaseCreature bcTarget)
            {
                Dbg(PassiveDebugFlags.Gate, $"DENY credit (target not BaseCreature) target={GetSafeName(target)}");
                return;
            }

            if (bcTarget.Controlled || bcTarget.Summoned)
            {
                Dbg(PassiveDebugFlags.Gate, $"DENY credit (target controlled/summoned) target={GetSafeName(target)}");
                return;
            }

            // Do not award engagement credit for damage to a player's own pets (or friendly sparring)
            if (IsOwnerControlledPetTarget(pm, target))
            {
                Dbg(PassiveDebugFlags.Gate,
                    $"DENY credit (target is owner-controlled pet) source=Engagement target={GetSafeName(target)}");
                return;
            }

            // Source-wide “no gyms / no house macros / no mods” rule
            if (!CanAwardPassiveCredit(pm, PlayerMobile.PassiveGainSource.Engagement, out deny))
            {
                Dbg(PassiveDebugFlags.Gate, $"DENY credit ({deny}) source=Engagement");
                return;
            }

            // Kill-resolution gate (completion event):
            // Lethal hits are evaluated immediately and independently of engagement cooldown.
            // Passing this gate confirms the kill qualified (presence + contribution) and
            // that any associated credit is banked, even if no immediate skill gain occurs.
            // See EarnedKillReward() for eligibility policy.
            bool killBonus = false;

            if (willKill)
            {
                if (!pm.EarnedKillReward(target, out string reason))
                {
                    Dbg(PassiveDebugFlags.Gate, $"DENY kill-reward target={target} ({reason})");
                }
                else
                {
                    Dbg(PassiveDebugFlags.Gate, $"ALLOW kill-reward target={target} ({reason})");
                    killBonus = true;
                }

                // eligible: award kill bonus (later)
            }

            // Unified cooldown gate (engagement is high-frequency; keep conservative)
            // Exempt only when the kill-reward policy is satisfied.
            if (killBonus)
            {
                // Kill-qualified lethal hits are intentionally allowed to “pierce” the engagement cooldown.
                // This ensures the completion signal is always banked when earned (even if no gain occurs).
                Dbg(PassiveDebugFlags.Gate, "BYPASS cooldown (kill-reward qualified) source=Engagement");
            }
            else
            {
                if (!CooldownGate(new PassiveCreditKey(PassiveCreditKind.Engagement),
                         +TimeSpan.FromMilliseconds(CoreAI.GaveDamageCoolMs),
                         "engagement"))
                    return;
            }

            // Do not compute or forward passive credit if the destination skill cannot currently gain (locked or at cap).
            if (!pm.CanAccruePassiveProgression(PlayerMobile.PassiveProgressionBucket.AnimalTaming, out deny))
            {
                Dbg(PassiveDebugFlags.Gate, $"DENY accrue bucket=AnimalTaming source=Engagement ({deny})");
                return;
            }

            // Compute engagement credit for this interaction.
            // This is the authoritative difficulty-scaled valuation (pure function).
            // Diagnostic components are captured for logging and tuning; no policy
            // decisions (cooldowns, kill bonuses, gain rolls) are applied here.
            double points = ComputeEngagementPoints(pet: this, target: target,
                out double basePoints,
                out double mult,
                out double ratio,
                out double petPower,
                out double tgtPower);

            Dbg(PassiveDebugFlags.Points,
                $"POINTS computed={points:0.###} source=Engagement bucket=AnimalTaming (base={basePoints:0.###} mult={mult:0.###} ratio={ratio:0.###} pPet={petPower:0.##} pTar={tgtPower:0.##})");

            pm.AddPassivePoints(
                PlayerMobile.PassiveGainSource.Engagement,
                PlayerMobile.PassiveProgressionBucket.AnimalTaming,
                points,
                pet: this,
                context: target);

            Dbg(PassiveDebugFlags.Forwarding, "FORWARDED to PlayerMobile.AddPassivePoints(source=Engagement)");

            // Optional kill completion bonus (earned + presence verified; not subject to engagement cooldown).
            if (killBonus)
            {
                double bonus = ComputeEngagementKillBonus(points);

                pm.AddPassivePoints(
                    PlayerMobile.PassiveGainSource.Engagement, // or PassiveGainSource.Kill later
                    PlayerMobile.PassiveProgressionBucket.AnimalTaming,
                    bonus,
                    pet: this,
                    context: target);

                Dbg(PassiveDebugFlags.Forwarding, "FORWARDED to PlayerMobile.AddPassivePoints(source=Engagement.Kill)");

                Dbg(PassiveDebugFlags.Points,
                    $"POINTS bonus={bonus:0.###} source=Engagement.Kill bucket=AnimalTaming (basePts={points:0.###})");
            }

        }

        // ========================================================================================
        // Point computation (policy placeholders)
        // ========================================================================================
        // --------------------------------------------------------------------
        // Points policy (rough-in):
        //  - Small fixed base (frequent signal)
        //  - Scaled by Power ratio (harder fights => more)
        //  - Hard clamped to prevent runaway / edge abuse
        //
        // Note:
        // PlayerMobiles do not expose Power. For non-creature targets (e.g., players),
        // use a minimal effective power derived from the pet's Power. This:
        //  - Keeps the ratio math well-defined
        //  - Strongly devalues "friendly sparring" or player targets
        //  - Avoids introducing a synthetic Power model for players
        // --------------------------------------------------------------------
        private static double ComputeEngagementPoints(
            BaseCreature pet,
            Mobile target,
            out double basePoints,
            out double mult,
            out double ratio,
            out double petPower,
            out double tgtPower)
        {
            basePoints = 0.124;

            petPower = Math.Max(1.0, pet.Power);

            if (target is BaseCreature bc)
                tgtPower = Math.Max(1.0, bc.Power);
            else
                tgtPower = Math.Max(1.0, petPower * 0.25);

            ratio = tgtPower / petPower;

            if (ratio < 0.25) ratio = 0.25;
            if (ratio > 4.00) ratio = 4.00;

            mult = Math.Sqrt(ratio);

            if (mult < 0.50) mult = 0.50;
            if (mult > 1.75) mult = 1.75;

            double points = basePoints * mult;

            if (points < 0.01) points = 0.01;
            if (points > 0.15) points = 0.15;

            return points;
        }
        private static double ComputeEngagementKillBonus(double engagementPoints)
        {
            // Kill completion bonus:
            // - Scaled to the fight (derived from computed engagement value)
            // - Intended to be *noticeable at the margin* without becoming dominant
            // - Still bounded so kills cannot become the primary progression strategy
            const double KillBonusMult = 0.75;

            // Absolute cap to prevent domination in high-value fights.
            const double KillBonusCap = 0.08;

            // Ensure the bonus is not mathematically invisible when legitimately earned.
            const double KillBonusMin = 0.01;

            double bonus = engagementPoints * KillBonusMult;

            if (bonus > KillBonusCap)
                bonus = KillBonusCap;
            else if (bonus < KillBonusMin)
                bonus = KillBonusMin;

            return bonus;
        }

        private static double ComputePassivePointsFromPetHeal(int healed)
        {
            if (healed <= 0)
                return 0.0;

            // Supportive-only: healing reinforces proper pet handling but must not become a primary loop.
            // Use diminishing returns so very large heals do not spike rewards.
            //
            // Typical outcomes:
            //  healed  5  -> ~0.043
            //  healed 10  -> ~0.052
            //  healed 25  -> ~0.070
            //  healed 50  -> ~0.090
            //  healed 80  -> ~0.106
            double basePts = 0.02;
            double scaled = Math.Sqrt(healed);         // diminishing returns
            double points = basePts + (0.01 * scaled); // tune coefficient as needed

            // Local cap: should rarely touch global pre-engagement cap.
            if (points > 0.12)
                points = 0.12;

            return points;
        }

        private static double ComputePassivePointsFromPetCure(Poison oldPoison)
        {
            // Supportive-only: curing reinforces proper pet handling but must not become a primary loop.
            // Scale modestly with poison severity (Lesser..Lethal), but keep below the pre-engagement cap.
            //
            // Levels (your shard):
            //  0 Lesser  -> 0.08
            //  1 Regular -> 0.09
            //  2 Greater -> 0.10
            //  3 Deadly  -> 0.11
            //  4 Lethal  -> 0.12

            int lvl = 0;

            // Many code paths pass a Poison instance; PoisonImpl exposes Level via Poison.Level on most forks.
            if (oldPoison != null)
                lvl = oldPoison.Level;

            if (lvl < 0) lvl = 0;
            if (lvl > 4) lvl = 4;

            return 0.08 + (0.01 * lvl);
        }

        private static double ComputePassivePointsFromPetStatGain(StatType stat, int delta)
        {
            if (delta <= 0)
                return 0.0;

            // Supportive-only: pet stat gains are a background reinforcement (Engagement is primary).
            // Keep values well below the global pre-engagement cap; use diminishing returns to prevent spikes.
            double basePts = 0.02;
            double scaled = Math.Sqrt(delta);        // delta is typically small; sqrt keeps bursts tame
            double points = basePts + (0.04 * scaled); // delta=1 -> ~0.06, delta=4 -> ~0.10

            // Optional: discount farmable stats if needed.
            // if (stat == StatType.Int) points *= 0.75;

            if (points > 0.12)
                points = 0.12;

            return points;
        }

        private static double ComputePassivePointsFromPetGain(Skill skill, double delta)
        {
            if (delta <= 0.0)
                return 0.0;

            // Supportive-only signal: pet skill gains reinforce owner training,
            // but must not become a primary progression loop.
            //
            // Use diminishing returns on delta to avoid burst abuse.
            // Typical outcomes:
            //  delta 0.1 -> ~0.04
            //  delta 0.4 -> ~0.06
            //  delta 1.0 -> ~0.08
            double basePts = 0.02;
            double scaled = Math.Sqrt(delta);      // diminishing returns
            double points = basePts + (0.06 * scaled);

            // Exploit resistance by skill family
            // Combat-facing skills pay full value; passive/utility skills pay less.
            switch (skill.SkillName)
            {
                case SkillName.Wrestling:
                case SkillName.Tactics:
                case SkillName.Anatomy:
                case SkillName.MagicResist:
                    // full value
                    break;

                case SkillName.Meditation:
                    //case SkillName.Focus:
                    points *= 0.5;
                    break;

                default:
                    // Unknown or utility skills: conservative
                    points *= 0.75;
                    break;
            }

            // Local cap: should almost never touch the global pre-engagement cap
            if (points > 0.12)
                points = 0.12;

            return points;
        }



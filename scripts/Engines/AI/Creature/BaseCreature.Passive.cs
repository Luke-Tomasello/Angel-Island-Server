        public static PassiveDebugFlags PassiveDebugFlagsGlobal = PassiveDebugFlags.All;

        private string GetPassiveLogFileName()
        {
            string masterName = (ControlMaster != null) ? ControlMaster.Name : "NoMaster";
            int masterSerial = (ControlMaster != null) ? ControlMaster.Serial.Value : 0;

            // Sanitize for filesystem (keep it simple)
            string safeName = SanitizeFilePart(masterName);

            return $"{safeName}_0x{masterSerial:X}_PassiveGains.log";
        }

        private static string SanitizeFilePart(string s)
        {
            if (string.IsNullOrWhiteSpace(s))
                return "Unknown";

            foreach (char c in Path.GetInvalidFileNameChars())
                s = s.Replace(c, '_');

            return s.Trim();
        }

        private void Dbg(PassiveDebugFlags flag, string msg)
        {
            if (!CoreAI.IsDynamicFeatureSet(CoreAI.FeatureBits.LogPassiveGains))
                return;

            if ((PassiveDebugFlagsGlobal & flag) == 0)
                return;

            string pet = GetSafeName(this);
            string master = (ControlMaster != null) ? GetSafeName(ControlMaster) : "<no master>";

            string file = GetPassiveLogFileName();

            LogHelper logger = new LogHelper(file, overwrite: false, sline: false);
            logger.Log(LogType.Text, $"[Passive:{flag}] pet={pet} master={master} :: {msg}");
            logger.Finish();
        }

        private static string GetSafeName(Mobile? m)
        {
            if (m == null)
                return "<null>";
            if (m.Deleted)
                return "<deleted>";
            try
            {
                if (!string.IsNullOrEmpty(m.Name))
                    return $"{m.Name}({m.Serial})";
                return $"{m.GetType().Name}({m.Serial})";
            }
            catch
            {
                return "<name-ex>";
            }
        }

